/*
 * =========================================================
 * JESSICA CORE BACKEND
 * =========================================================
 *
 * Главная точка запуска backend.
 *
 *
 * Здесь остаётся только:
 *
 * - Environment;
 * - Express;
 * - Tools initialization;
 * - HTTP routes;
 * - запуск сервера;
 * - необязательные startup diagnostics.
 *
 *
 * Вся конкретная логика вынесена
 * в отдельные модули.
 *
 * =========================================================
 */


/*
 * =========================================================
 * ENVIRONMENT
 * =========================================================
 *
 * Environment загружается до Jessica Tools
 * и остальных модулей.
 *
 * =========================================================
 */


import "dotenv/config";


/*
 * =========================================================
 * EXPRESS
 * =========================================================
 */


import express from "express";


/*
 * =========================================================
 * TOOLS INITIALIZATION
 * =========================================================
 *
 * При импорте регистрируются все инструменты
 * Jessica в Tool Registry.
 *
 * =========================================================
 */


import "./tools/initTools.js";


/*
 * =========================================================
 * ROUTES
 * =========================================================
 */


import {
    registerRoutes
} from "./http/routes/registerRoutes.js";


/*
 * =========================================================
 * TOOL REGISTRY
 * =========================================================
 *
 * Здесь нужен только для стартового лога.
 *
 * =========================================================
 */


import {
    listTools
} from "./tools/toolRegistry.js";


/*
 * =========================================================
 * STARTUP DIAGNOSTICS
 * =========================================================
 *
 * Временный Learning-тест.
 *
 * Сам модуль проверяет:
 *
 * RUN_LEARNING_TEST_ON_START=true
 *
 * Если флаг выключен,
 * ничего не происходит.
 *
 * =========================================================
 */


import {
    runStartupLearningTest
} from "./scripts/startupLearningTest.js";


/*
 * =========================================================
 * APPLICATION
 * =========================================================
 */


const app =
    express();


/*
 * =========================================================
 * JSON
 * =========================================================
 */


app.use(

    express.json({

        limit:
            "1mb"

    })

);


/*
 * =========================================================
 * ROUTE CHAIN
 * =========================================================
 */


registerRoutes(
    app
);


/*
 * =========================================================
 * PORT
 * =========================================================
 */


const port =
    Number(
        process.env.PORT
    ) || 3000;


/*
 * =========================================================
 * START
 * =========================================================
 */


app.listen(
    port,
    () => {


        /*
         * =================================================
         * TOOLS
         * =================================================
         */


        const tools =
            listTools()
                .map(
                    tool =>
                        tool.name
                );


        console.log(
            `Jessica Core started on port ${port}`
        );


        console.log(

            `Jessica tools (${tools.length}):`,

            tools.join(
                ", "
            )

        );


        /*
         * =================================================
         * OPTIONAL STARTUP LEARNING TEST
         * =================================================
         *
         * ВАЖНО:
         *
         * не используем await.
         *
         * Backend уже запущен и готов
         * принимать запросы.
         *
         * Ошибка диагностического теста
         * не должна останавливать Jessica.
         *
         * =================================================
         */


        runStartupLearningTest()
            .catch(
                error => {


                    console.error(
                        "Jessica startup diagnostic error:",
                        error
                    );


                }
            );


    }
);
