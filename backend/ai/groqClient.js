import OpenAI from "openai";


/*
 * =========================================================
 * JESSICA GROQ CLIENT
 * =========================================================
 *
 * Единая точка подключения Jessica к Groq.
 *
 *
 * Используется AI-модулями:
 *
 * - Planner;
 * - Learning Analyzer;
 * - будущими специализированными AI-модулями.
 *
 *
 * Этот файл отвечает только за:
 *
 * - создание Groq/OpenAI-compatible клиента;
 * - проверку наличия GROQ_API_KEY;
 * - повторное использование одного клиента.
 *
 *
 * Этот файл НЕ:
 *
 * - выбирает модель для конкретной задачи;
 * - содержит prompts;
 * - выполняет Planner;
 * - выполняет Learning;
 * - парсит ответы модели.
 *
 * =========================================================
 */


/*
 * =========================================================
 * CONFIG
 * =========================================================
 */


const GROQ_BASE_URL =
    "https://api.groq.com/openai/v1";


/*
 * =========================================================
 * CLIENT CACHE
 * =========================================================
 */


let groqClient =
    null;


/*
 * =========================================================
 * GET GROQ CLIENT
 * =========================================================
 */


export function getGroqClient() {


    /*
     * Уже созданный клиент
     * используем повторно.
     */


    if (groqClient) {

        return groqClient;

    }


    /*
     * =====================================================
     * API KEY
     * =====================================================
     */


    const apiKey =
        String(
            process.env.GROQ_API_KEY || ""
        ).trim();


    if (!apiKey) {

        throw new Error(
            "GROQ_API_KEY не настроен"
        );

    }


    /*
     * =====================================================
     * CREATE CLIENT
     * =====================================================
     */


    groqClient =
        new OpenAI({

            apiKey,

            baseURL:
                GROQ_BASE_URL

        });


    return groqClient;

}
