/*
 * Repair only the defective statements of a source-grounded comparison.
 * The generic Composer stays unchanged, while this small module is
 * available only for failed two-source validation.
 */
export function buildComparisonRepairHints(reason) {
 const r=String(reason||"");
 if(!r.trim())return "";
 const rules=[
  "РЕЖИМ ИСПРАВЛЕНИЯ СРАВНЕНИЯ:",
  "Заменяй каждую ошибочную ячейку на конкретный юридический вывод, подтверждённый дословным положением её источника.",
  "Не отвечай «описано в разделе», «в тех же пунктах» или только цитатой без объяснения, что именно разрешено или обязательно.",
  "Не смешивай разрешение и обязанность; при нескольких разных утверждениях подтверждай каждое или оставляй только доказанную часть.",
  "Условные требования передавай вместе с условием if/when/provided that.",
  "Не превращай фразу «нет цитаты в приведённом фрагменте» в вывод об отсутствии нормы в документе.",
  "Если условие действительно нельзя проверить, напиши ровно «Не удалось подтвердить по прочитанному тексту».",
  "Обязательно сохрани Markdown-таблицу, оба документа и все запрошенные критерии."
 ];
 if(/уведомлен|notice|copyright|авторск/iu.test(r))
  rules.push("Для уведомлений отличай обязанность сохранить исходные сведения от разрешения добавить свои; различай сохранение существующих уведомлений и условную обязанность воспроизвести сведения из отдельного файла, если он имеется. Не заявляй, что необходимо сохранить сам файл, без прямого подтверждения.");
 if(/распростран|distribution|distribut/iu.test(r))
  rules.push("Для распространения объясни что можно распространять и какие условия нужно соблюсти, а не где эти условия описаны.");
 return rules.join("\n");
}
