/*
 * Separation-of-concerns guidance for evidence-backed comparison rows.
 * Designed for two-source legal/rights comparisons, not specific license
 * names. Prevents an AI from restating neighboring facts in each cell.
 */
const RULES={
  use: "ИСПОЛЬЗОВАНИЕ: укажи только разрешённые действия: использовать, копировать, изменять, создавать производные. Условия сохранения уведомлений не повторяй здесь — они относятся к строке «Уведомления». Не пиши «без ограничений» при наличии условий лицензии.",
  distribution: "РАСПРОСТРАНЕНИЕ: сообщи разрешённые формы распространения и подтверждённые условия. Не добавляй права на собственный copyright, если для этого нет отдельной цитаты.",
  notices: "УВЕДОМЛЕНИЯ: различай сохранение исходных уведомлений, передачу текста лицензии и условное включение содержимого файла NOTICE. Не превращай «если файл NOTICE имеется» в безусловное требование иметь такой файл.",
  patents: "ПАТЕНТЫ: отдельно объясни предоставление патентных прав и условия их прекращения. Если по второму источнику нет цитат, не делай вывод об отсутствии патентных условий.",
  restrictions: "ОГРАНИЧЕНИЯ: укажи только подтверждённые запреты, например на использование названий или товарных знаков. Не добавляй отказ от гарантий и ответственности без отдельной выдержки с warranty / AS IS / liability. Не путай разрешение на обозначение происхождения с полным запретом.",
  warranty: "ГАРАНТИИ: утверждение об отсутствии гарантий подтверждай отдельным положением о warranty или AS IS.",
  obligations: "ОБЯЗАННОСТИ: каждая обязанность требует цитаты с must/shall или другим недвусмысленным нормативным действием."
};
export function comparisonCriterionGuidance(criteria) {
  const ids=new Set((Array.isArray(criteria)?criteria:[]).map(row=>String(row?.id||"")));
  if(!ids.size)return "";
  const out=["РАЗГРАНИЧЕНИЕ КРИТЕРИЕВ ТАБЛИЦЫ:"];
  for(const [id,rule] of Object.entries(RULES))if(ids.has(id))out.push(rule);
  out.push("Одна ячейка — один компактный доказанный вывод. Если есть независимый дополнительный факт, вынеси его в подходящую строку или исключи при отсутствии подтверждения.");
  return out.join("\n");
}
