/* Compact, cell-ID keyed source verification. Never certify an
 * unsupported fact or invent a claim missing from the final answer. */
export function buildComparisonCellCheckPrompt(){
  return [
    "Ты независимый Validator для сравнения двух документов.",
    "Даны фактические ячейки таблицы с ID и номерами SOURCE.",
    "Проверяй только написанное в этих ячейках, каждый ID ровно один раз.",
    "Ответ только JSON: {\"c\":[[1,[\"дословная цитата\"]],[2,[]]]}.",
    "Для каждого ID верни массив из 1–3 дословных цитат из указанного SOURCE.",
    "Одна цитата: 5–35 соседних слов; для условия if/when приводи часть с условием и действием. Без многоточий.",
    "Если ячейка содержит два независимых факта, оба должны быть подтверждены цитатами.",
    "Например, для патентного гранта и его прекращения найди оба положения.",
    "Для требования к исходной и бинарной формам приведи подтверждение обеих форм.",
    "Для обязанности цитируй must/shall/retain/include и соответствующее действие.",
    "Для предоставления права (grant) найди grant, не подменяй его must.",
    "Для условной обязанности сохрани условие if/when в доказательствах.",
    "Если хотя бы часть ячейки не доказана — верни [] для данного ID.",
    "Не доказывай отсутствие положения молчанием источника.",
    "Не добавляй explanations, claims или текст вне JSON. Ответ короткий."
  ].join("\n");
}
export function buildComparisonCellCheckRequest(task,matrix,sourceText){
  return ["ЗАДАЧА:",String(task||""),"",
    "ПРОВЕРЯЕМЫЕ ЯЧЕЙКИ:",
    ...matrix.checks.map(c=>`${c.id}. SOURCE ${c.source+1}; ${c.criterion}: ${c.value}`),
    "","ПЕРВОИСТОЧНИКИ:",sourceText].join("\n");
}
