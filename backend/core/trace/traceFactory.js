/*
 * =========================================================
 * JESSICA TRACE FACTORY v2
 * =========================================================
 *
 * Создание Execution Trace.
 *
 *
 * Ответственность:
 *
 * - создать новый Trace;
 * - определить начальную структуру;
 * - определить начальные значения.
 *
 *
 * НЕ:
 *
 * - записывает события;
 * - записывает Result;
 * - завершает Trace;
 * - создаёт Learning Payload.
 *
 * =========================================================
 */


import {
    randomUUID
} from "node:crypto";


/*
 * =========================================================
 * CREATE TRACE
 * =========================================================
 */


export function createExecutionTrace(
    task
) {

    return {

        /*
         * =================================================
         * IDENTITY
         * =================================================
         */


        id:

            randomUUID(),


        task:

            String(
                task || ""
            )
            .trim(),


        startedAt:

            new Date()
                .toISOString(),


        finishedAt:

            null,


        status:

            "RUNNING",


        /*
         * =================================================
         * HISTORY
         * =================================================
         */


        events:

            [],


        attempts:

            [],


        steps:

            [],


        /*
         * =================================================
         * ACTUAL TOOL EVIDENCE
         * =================================================
         *
         * Здесь хранятся только инструменты,
         * которые действительно были выполнены.
         *
         * Это НЕ список tools из Planner Plan.
         *
         * Пример:
         *
         * [
         *   "web_search",
         *   "web_fetch"
         * ]
         *
         * =================================================
         */


        executedTools:

            [],


        failures:

            [],


        replans:

            [],


        /*
         * =================================================
         * RESULT
         * =================================================
         */


        result:

            null,


        validation:

            null,


        terminal:

            null,


        /*
         * =================================================
         * CONTEXT
         * =================================================
         */


        contextSnapshot: {

            executionId:

                null,


            initialPlan:

                null,


            currentPlan:

                null

        },


        /*
         * =================================================
         * EXPERIENCE
         * =================================================
         *
         * found:
         * Experience был найден.
         *
         * used:
         * текущее compatibility-поле.
         *
         * Позже отдельно введём applied,
         * который будет означать фактическое
         * выполнение требований Experience.
         *
         * =================================================
         */


        experienceUsage: {

            used:

                false,


            found:

                false,


            source:

                null,


            confidence:

                0,


            skills:

                [],


            skillIds:

                []

        },


        /*
         * =================================================
         * STATISTICS
         * =================================================
         */


        statistics: {

            attempts:

                0,


            retries:

                0,


            replans:

                0,


            completed:

                0,


            failed:

                0

        },


        /*
         * =================================================
         * LEARNING
         * =================================================
         */


        learningReady:

            false

    };

}
