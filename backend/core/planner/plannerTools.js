import {
    listTools
} from "../../tools/toolRegistry.js";


/*
 * =========================================================
 * JESSICA PLANNER TOOLS
 * =========================================================
 *
 * Подготавливает описание инструментов
 * для Planner.
 *
 * Не содержит:
 *
 * - AI запросов
 * - логики планирования
 * - Experience
 * - нормализации
 * - валидации
 *
 * =========================================================
 */


export function buildToolsText() {


    const tools =
        listTools();


    /*
     * =====================================================
     * NO TOOLS
     * =====================================================
     */


    if (
        tools.length === 0
    ) {


        return "Инструменты отсутствуют.";


    }



    /*
     * =====================================================
     * TOOL DESCRIPTIONS
     * =====================================================
     *
     * Каждый инструмент передаётся Planner
     * отдельным JSON объектом.
     *
     * =====================================================
     */


    return tools
        .map(
            tool => {


                return JSON.stringify({

                    name:
                        tool.name,

                    description:
                        tool.description,

                    arguments:
                        tool.arguments || {}

                });


            }
        )
        .join(
            "\n"
        );


}
