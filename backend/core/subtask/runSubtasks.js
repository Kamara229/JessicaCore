import {
    executeSubtask
} from "./executeSubtask.js";

import {
    buildSubtaskSummary
} from "./subtaskSummary.js";


/*
 * =========================================================
 * JESSICA RUN SUBTASKS
 * =========================================================
 *
 * Последовательно выполняет несколько подзадач.
 *
 *
 * Рабочая цепочка:
 *
 * decomposition
 *      ↓
 * subtasks[]
 *      ↓
 * executeSubtask()
 *      ↓
 * results[]
 *      ↓
 * buildSubtaskSummary()
 *
 *
 * Этот модуль НЕ:
 *
 * - вызывает Planner напрямую;
 * - работает с Experience напрямую;
 * - выполняет инструменты;
 * - считает статистику самостоятельно;
 * - формирует финальный ответ пользователю.
 *
 * =========================================================
 */


/*
 * =========================================================
 * RUN ALL SUBTASKS
 * =========================================================
 */


export async function runSubtasks(
    decomposition
) {


    /*
     * =====================================================
     * SUBTASKS
     * =====================================================
     */


    const subtasks =
        Array.isArray(
            decomposition?.subtasks
        )
            ? decomposition.subtasks
            : [];


    /*
     * =====================================================
     * NO SUBTASKS
     * =====================================================
     */


    if (
        subtasks.length === 0
    ) {

        return buildSubtaskSummary(
            []
        );

    }


    /*
     * =====================================================
     * RESULTS
     * =====================================================
     */


    const results =
        [];


    /*
     * =====================================================
     * SEQUENTIAL EXECUTION
     * =====================================================
     *
     * Пока подзадачи выполняются последовательно.
     *
     * Причины:
     *
     * - меньше нагрузка на AI API;
     * - проще контролировать rate limits;
     * - проще анализировать логи;
     * - retry одной подзадачи
     *   не мешает другим;
     * - Experience каждой подзадачи
     *   определяется независимо.
     *
     * =====================================================
     */


    for (
        const subtask
        of subtasks
    ) {


        console.log(

            `Jessica subtask ${subtask?.id}:`,

            subtask?.text

        );


        try {


            /*
             * =================================================
             * EXECUTE
             * =================================================
             */


            const result =
                await executeSubtask(
                    subtask
                );


            results.push(
                result
            );


        } catch (error) {


            /*
             * =================================================
             * UNHANDLED ERROR
             * =================================================
             *
             * Ошибка одной подзадачи
             * не должна останавливать остальные.
             *
             * =================================================
             */


            console.error(

                `Unhandled subtask error ${subtask?.id}:`,

                error

            );


            results.push({

                id:
                    subtask?.id ?? null,

                text:
                    typeof subtask?.text === "string"
                        ? subtask.text
                        : "",

                status:
                    "FAILED",

                success:
                    false,

                stage:
                    "subtask",

                result:
                    "Непредвиденная ошибка выполнения подзадачи"

            });


        }


    }


    /*
     * =====================================================
     * SUMMARY
     * =====================================================
     */


    return buildSubtaskSummary(
        results
    );


}
