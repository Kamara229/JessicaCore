def new_novel48_source_only():
    rows=tuple({"row_id":f"S79_{i:02d}","text":text}
               for i,text in enumerate(SOURCE_TEXTS,1))
    if (len(rows)!=48 or len({r["text"] for r in rows})!=48
            or len({r["row_id"] for r in rows})!=48
            or any(set(r)!={"row_id","text"} or
                   len(r["text"])<25 or len(r["text"])>220
                   or "  " in r["text"]
                   for r in rows)):
        raise ValueError("S79 source-only 48 unique Russian stress cases not frozen")
    return rows


def new_novel48_source_sha256():
    raw=json.dumps(new_novel48_source_only(),
                   ensure_ascii=False,sort_keys=True,separators=(",",":"))
    return hashlib.sha256(raw.encode("utf8")).hexdigest()
