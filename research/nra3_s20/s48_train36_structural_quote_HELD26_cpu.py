def require(ok,why):
    if not bool(ok):
        raise ValueError("S48 TRAIN36 HELD26 physical quote control: "+why)


def token_gold_from_manual(tokens,spans):
    """Use handwritten char ranges; never derive gold via quote parser."""
    for a,b in spans:
        require(0<=a<b<=tokens[-1].end,"invalid manual gold span")
    return torch.tensor([any(a<=t.start and t.end<=b for a,b in spans)
                         for t in tokens],dtype=torch.bool)


class StructuralQuoteReadout(nn.Module):
    """New 4-scalar readout over text-only 3-feature quote representation.

    The complete structural matched bit is generated by S48 Unicode
    state graph without any gold; original S39 bit and frozen S45 logit
    remain as residual inputs. No learned tokenizer or online active NRA2.
    """
    def __init__(self):
        super().__init__()
        self.structural_raw_strength=nn.Parameter(torch.tensor(0.))
        self.legacy_raw_strength=nn.Parameter(torch.tensor(-2.))
        self.frozen_neural_strength=nn.Parameter(torch.tensor(-2.))
        self.bias=nn.Parameter(torch.tensor(0.))
        self.output_gate=0
        self.candidate_accepted=False
        self.activation_allowed=False

    def forward(self,frozen_logit,legacy_raw,structural_raw):
        require(frozen_logit.shape==legacy_raw.shape==structural_raw.shape,
                "text-only structural quote feature geometry drift")
        require(bool(((legacy_raw==0)|(legacy_raw==1)).all())
                and bool(((structural_raw==0)|(structural_raw==1)).all()),
                "raw punctuation quote membership must be binary")
        return (F.softplus(self.structural_raw_strength)*(2*structural_raw-1)
                +F.softplus(self.legacy_raw_strength)*(2*legacy_raw-1)
                +F.softplus(self.frozen_neural_strength)*torch.tanh(frozen_logit)
                +self.bias)


def text_features(frozen_s45,row_text):
    tok=raw_surface_grammar(row_text)
    x,q,p=raw_token_pair_features(row_text)
    st=plain_scope_features(row_text)
    matched=matched_quote_graph_from_raw(row_text)
    require(len(tok)==q.shape[0]==matched.content.shape[0],
            "S48 independent quote scanner tokenizer misaligned")
    with torch.inference_mode():
        old_logit=frozen_s45(x,q,p,st).quote_logits.detach()
    require(old_logit.shape==matched.content.shape==q[:,0].shape,
            "text-derived quote shapes differ")
    return tok,old_logit,q[:,0],matched.content,matched


def stats(pred,gold):
    tp=int((pred&gold).sum())
    fp=int((pred&~gold).sum())
    fn=int((~pred&gold).sum())
    return {"TP":tp,"FP":fp,"FN":fn}


def total(records,key):
    tp=sum(r[key]["TP"] for r in records)
    fp=sum(r[key]["FP"] for r in records)
    fn=sum(r[key]["FN"] for r in records)
    return {"TP":tp,"FP":fp,"FN":fn,
            "precision":tp/(tp+fp) if tp+fp else 0.,
            "recall":tp/(tp+fn) if tp+fn else 0.,
            "F1":2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else 0.}


def fit_train36_readout(frozen,rows):
    all_old=[]
    all_raw=[]
    all_graph=[]
    all_gold=[]
    for row in rows:
        tok,old,raw,graph,_=text_features(frozen,row.text)
        gold=token_gold_from_manual(tok,row.gold_char_spans)
        all_old.append(old)
        all_raw.append(raw)
        all_graph.append(graph)
        all_gold.append(gold)
    old=torch.cat(all_old).detach()
    raw=torch.cat(all_raw).detach()
    graph=torch.cat(all_graph).detach()
    gold=torch.cat(all_gold)
    require(bool(gold.any()) and bool((~gold).any()),
            "TRAIN36 must contain both positive and negative quote tokens")
    torch.manual_seed(481118)
    readout=StructuralQuoteReadout()
    require(sum(p.numel() for p in readout.parameters())==4,
            "S48 must fit exactly four quote parameters")
    optimizer=torch.optim.AdamW(readout.parameters(),lr=READOUT_LR,weight_decay=0.)
    old_loss=None
    for step in range(READOUT_STEPS):
        optimizer.zero_grad(set_to_none=True)
        scores=readout(old,raw,graph)
        loss=(F.softplus(-scores[gold]).mean()
              +F.softplus(scores[~gold]).mean()
              +TRAIN_L2*sum(p.square() for p in readout.parameters()))
        require(bool(torch.isfinite(loss)),"nonfinite TRAIN36 quote objective")
        loss.backward()
        require(all(p.grad is not None and bool(torch.isfinite(p.grad).all())
                    for p in readout.parameters()),
                "missing finite gradients in small S48 readout")
        optimizer.step()
        if step==0:old_loss=float(loss.detach())
    readout.eval()
    with torch.no_grad():
        final_train=stats(readout(old,raw,graph)>=0,gold)
    diagnostic={
        "TRAIN_loss_initial":old_loss,
        "TRAIN_loss_final":float(loss.detach()),
        "TRAIN36_raw_only_structural_quote":stats(graph>.5,gold),
        "TRAIN36_fitted_quote":final_train,
        "TRAIN36_tokens":len(old),
        "train_steps":READOUT_STEPS,
        "lr":READOUT_LR,
        "trained_scalar_count":4,
        "fit_weights_sha256":hashlib.sha256(b"".join(
            p.detach().cpu().contiguous().numpy().tobytes()
            for p in readout.parameters())).hexdigest(),
        "structural_coefficient":float(F.softplus(readout.structural_raw_strength).detach()),
        "legacy_coefficient":float(F.softplus(readout.legacy_raw_strength).detach()),
        "frozen_neural_coefficient":float(F.softplus(readout.frozen_neural_strength).detach()),
        "bias":float(readout.bias.detach()),
    }
    return readout,diagnostic


def score_held(row,frozen_s45,s46_calibration,s48_readout):
    tok,old,raw,graph,detail=text_features(frozen_s45,row.text)
    with torch.inference_mode():
        s46=s46_calibration(old,raw)
        s48=s48_readout(old,raw,graph)
    gold=token_gold_from_manual(tok,row.gold_char_spans)
    predictions={
        "S39_raw_unicode_quote_bit":raw>.5,
        "S45_original_neural_quote_head":old>=0,
        "S46_old_train_scalar_quote":s46>=0,
        "S48_new_matched_structural_graph":graph>.5,
        "S48_TRAIN36_fitted_structural_readout":s48>=0,
    }
    entry={"case_id":row.row_id,"category":row.category,
           "text_HELD_NOT_TRAINED":row.text,
           "gold_manual_char_spans_OFFLINE_ONLY":row.gold_char_spans,
           "gold_manual_token_indices_OFFLINE_ONLY":torch.nonzero(gold).flatten().tolist(),
           "raw_features_only_no_gold_in_any_forward":True,
           "matched_graph_accepted_pairs":detail.valid_outer_pairs,
           "matched_graph_dangling_openers":detail.dangling_openers,
           "matched_graph_ignored_apostrophes":detail.ignored_apostrophes,
           "matched_graph_ignored_escaped_marks":detail.ignored_escaped_quote_marks}
    for name,pred in predictions.items():
        entry[name]=stats(pred,gold)
        entry[name+"_predicted_indices"]=torch.nonzero(pred).flatten().tolist()
    return entry


