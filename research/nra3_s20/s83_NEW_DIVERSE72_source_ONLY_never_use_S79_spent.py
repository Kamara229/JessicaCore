def source_only_new72():
    out=tuple({
        "row_id":f"G{group+1:02d}_{i+1:02d}",
        "group":f"G{group+1:02d}",
        "text":text,
    } for group,rows in enumerate(GROUPS)
      for i,text in enumerate(rows))
    if (len(out)!=72
            or len({v["text"] for v in out})!=72
            or len({v["row_id"] for v in out})!=72
            or any(set(v)!={"row_id","group","text"} for v in out)
            or any(len(v["text"])<35 or len(v["text"])>210
                   for v in out)):
        raise ValueError("S83 NEW72 raw-only diverse source has inconsistent ABI")
    return out


