def require(condition,why):
    if not bool(condition):raise ValueError("S47 source-only frozen challenge: "+why)

def manual_token_gold(tokens,spans):
    """Gold only from separately authored character offsets, NEVER quote parser.

    This uses the same low-level Unicode tokenizer for offset alignment,
    but gold labels are NOT generated by any heuristic quote detector.
    """
    return torch.tensor([
        any(a<=t.start and t.end<=b for a,b in spans)
        for t in tokens],dtype=torch.bool)

def stats(pred, gold):
    tp=int((pred&gold).sum())
    fp=int((pred&~gold).sum())
    fn=int((~pred&gold).sum())
    return {"TP":tp,"FP":fp,"FN":fn}

def accumulate(rows,key):
    values=[r[key] for r in rows]
    tp=sum(v["TP"] for v in values)
    fp=sum(v["FP"] for v in values)
    fn=sum(v["FN"] for v in values)
    return {"TP":tp,"FP":fp,"FN":fn,
            "precision":tp/(tp+fp) if tp+fp else 0.,
            "recall":tp/(tp+fn) if tp+fn else 0.,
            "F1":2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else 0.}

def evaluate_case(row,frozen_s45,calibration):
    tokens=raw_surface_grammar(row.text)
    require(3<=len(tokens)<=40,"challenge sentence token count unsupported")
    pred,quote,pair=raw_token_pair_features(row.text)
    st=plain_scope_features(row.text)
    require(tuple(pred.shape)==(len(tokens),16)
            and tuple(quote.shape)==(len(tokens),5)
            and tuple(st.shape)==(len(tokens),len(tokens),12),
            "raw quote ABI and token alignment drift")
    with torch.inference_mode():
        old=frozen_s45(pred,quote,pair,st).quote_logits
        new=calibration(old,quote[:,0])
    raw=(quote[:,0]>.5)
    s45=(old>=0)
    s46=(new>=0)
    gold=manual_token_gold(tokens,row.gold_character_spans)
    scores={"raw_existing_unicode_quote_bit":stats(raw,gold),
            "S45_frozen_neural_quote":stats(s45,gold),
            "S46_frozen_TRAIN_calibrated_quote":stats(s46,gold)}
    return {
        "case_id":row.case_id,"category":row.category,
        "raw_text_NOT_A_TRAIN_SAMPLE":row.text,
        "tokens":[t.form for t in tokens],
        "manual_gold_character_spans":row.gold_character_spans,
        "manual_gold_token_indices_OFFLINE_ONLY":torch.nonzero(gold).flatten().tolist(),
        "raw_quote_token_indices":torch.nonzero(raw).flatten().tolist(),
        "S45_quote_token_indices":torch.nonzero(s45).flatten().tolist(),
        "S46_quote_token_indices":torch.nonzero(s46).flatten().tolist(),
        **scores,
        "no_gold_in_forward":True,
        "none_of_this_case_ever_used_for_training":True,
    }

