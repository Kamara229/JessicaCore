def pack_46m_from_s142(source: Path, packed_path: Path):
    """ONE true physical runtime file, complete all inherited tensors+new channels+NRA.

    Fixed-seed S132 down-projection is regenerated by the module, unchanged.
    The 24 new output channels really exist in the saved FP16, all initially 0.
    All NRA floating params, including the zero decoder, are paid and saved.
    """
    if packed_path.exists():
        raise FileExistsError("S197 immutable physical compressed checkpoint exists")
    inherited=load_file(str(source),device="cpu")
    ids=inherited[IDS_KEY]
    prior=inherited[WEIGHTS_KEY]
    if (ids.dtype!=torch.int32 or prior.dtype!=torch.float16
        or prior.shape!=(12,320,48)
        or tuple(ids.tolist())!=initial_active_indices(896)):
        raise AssertionError("S197 immutable S142 source must be exactly 48 active channels")
    full_indices=initial_active_indices(1344)
    if len(full_indices)!=72 or full_indices[:48]!=tuple(ids.tolist()):
        raise AssertionError("S197 rank1344 growth lost previously trained 48 channels")
    full=dict(inherited)
    full[IDS_KEY]=torch.tensor(full_indices,dtype=torch.int32)
    full[WEIGHTS_KEY]=torch.cat((prior,torch.zeros((12,320,24),dtype=torch.float16)),dim=-1)
    torch.manual_seed(197013)
    area=NeuroRepresentationArea().eval()
    for key,val in area.fp16_state().items():
        if key in full:
            raise AssertionError("S197 new learned region collides with old source weights")
        full[key]=val
    plain=save(full)
    packed=zlib.compress(plain,level=9)
    packed_path.parent.mkdir(parents=True,exist_ok=True)
    packed_path.write_bytes(packed)
    recovered_plain=zlib.decompress(packed_path.read_bytes())
    if recovered_plain!=plain:
        raise AssertionError("S197 packed runtime bytes changed after decompression")
    restored=load(recovered_plain)
    if (set(restored)!=set(full)
        or any(not torch.equal(restored[k],full[k]) for k in full)):
        raise AssertionError("S197 physical compressed runtime lost a weight")
    if not torch.equal(restored[WEIGHTS_KEY][:,:,:48],prior):
        raise AssertionError("S197 physical inherited S142 weights changed")
    if torch.count_nonzero(restored[WEIGHTS_KEY][:,:,48:]):
        raise AssertionError("S197 untrained new growth channels not exact-zero")
    return {
        "original_S142_size":source.stat().st_size,
        "original_S142_sha256":hashlib.sha256(source.read_bytes()).hexdigest(),
        "runtime_plain_bytes":len(plain),
        "runtime_packed_bytes":len(packed),
        "runtime_plain_sha256":hashlib.sha256(plain).hexdigest(),
        "runtime_packed_sha256":hashlib.sha256(packed).hexdigest(),
        "inherited_active_coefficients":48*12*320,
        "new_zero_active_coefficients":24*12*320,
        "area_physical_weight_count":AREA_PARAMS,
        "all_tensors_paid":len(restored),
    },restored


