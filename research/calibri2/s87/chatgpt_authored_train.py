def build_chatgpt_train(tok, *, max_new_tokens: int = 10):
    """Return a deterministic 64-row TRAIN-only corpus with full targets + EOS."""
    if tok.eos_token_id is None:
        raise AssertionError("Tokenizer must expose EOS for full-answer supervision")
    rows = []
    seen_questions = set()
    for task_id, answer, questions in TASKS:
        if len(questions) != 4 or not answer.endswith("."):
            raise AssertionError(f"Malformed ChatGPT TRAIN task: {task_id}")
        answer_ids = tok.encode(answer, add_special_tokens=False)
        if not answer_ids or len(answer_ids) + 1 > max_new_tokens:
            raise AssertionError(
                f"Full answer plus EOS exceeds generation budget: {task_id} "
                f"({len(answer_ids) + 1} tokens)"
            )
        for formulation, question in enumerate(questions, start=1):
            normalized = question.strip()
            if not normalized or normalized in seen_questions:
                raise AssertionError("Duplicate or empty ChatGPT TRAIN question")
            seen_questions.add(normalized)
            rows.append({
                "train_id": f"{task_id}/formulation_{formulation}",
                "task_id": task_id,
                "formulation": formulation,
                "question": normalized,
                "answer": answer,
            })
    if len(rows) != 64 or len(seen_questions) != 64:
        raise AssertionError("Expected exactly 16 tasks x 4 unique formulations")
    return rows
