"""CALIBRI session 10: image/video/3-D coding hypotheses on REAL MoE experts.

Pinned public Google switch-base-8 pretrained model, a single MoE layer's
8 independently trained wi matrices; no artificial inter-expert copying.
All ternary symbols are generated by a NAIVE threshold, and preserving
them is NOT equivalent to preserving original model quality.
"""
import hashlib
import json
import math
import pathlib
import re
import zlib
import numpy as np
import torch
from huggingface_hub import HfApi, hf_hub_download
from index import encode as cl8_encode, decode as cl8_decode
from benchmark import two_bit_zlib

MODEL="google/switch-base-8"
CKPT="pytorch_model.bin"
PATTERN=re.compile(r"decoder\.block\.1\.layer\.2\.mlp\.experts\.expert_(\d+)\.wi\.weight$")

def ternarize(w,zero=0.885):
    z=w.float().numpy()
    threshold=np.quantile(np.abs(z),zero,axis=1,keepdims=True)
    return np.where(np.abs(z)>threshold,np.sign(z),0).astype(np.int8)

def entropy(hist):
    h=np.asarray(hist,dtype=np.float64)
    p=h/h.sum()
    p=p[p>0]
    return float(-(p*np.log2(p)).sum())

def bitplanes(q):
    flat=q.reshape(-1)
    # positive/negative 1-bit indicator mask; two parallel binary planes
    p=np.packbits(flat==1,bitorder='little').tobytes()
    n=np.packbits(flat==-1,bitorder='little').tobytes()
    return len(zlib.compress(p+n,9))+12

def cond_entropy(a,b):
    # joint 3x3, estimated precisely from observed aligned positions.
    j=np.bincount(((a.ravel().astype(np.int16)+1)*3+
                   (b.ravel().astype(np.int16)+1)),minlength=9).reshape((3,3))
    hb=entropy(j.sum(axis=0))
    hj=entropy(j.reshape(-1))
    return {"mutual_information_bits_per_cell": max(0.,entropy(j.sum(axis=1))+hb-hj),
            "conditional_entropy_bits_per_cell":hj-entropy(j.sum(axis=1)),
            "joint_distribution":j.tolist()}

def main():
    rev=HfApi().model_info(MODEL).sha
    path=hf_hub_download(repo_id=MODEL,filename=CKPT,revision=rev)
    # SHA pinned to bytes, read streaming, no personal data.
    dig=hashlib.sha256()
    with open(path,'rb') as f:
        for buf in iter(lambda:f.read(1<<20),b""):dig.update(buf)
    sd=torch.load(path,map_location="cpu",weights_only=True)
    names=sorted([(int(PATTERN.match(k).group(1)),k) for k in sd
                  if PATTERN.match(k)])
    if len(names)!=8:raise ValueError(f"Expected 8 exact expert weights: got {len(names)}")
    base=None; records=[]; total=0; anchor_bytes=0; delta_bytes=0
    for eid,key in names:
        q=ternarize(sd[key])
        scales=4*q.shape[0]
        clb=cl8_encode(q)
        if not np.array_equal(q,cl8_decode(clb)):raise AssertionError('roundtrip')
        record={"expert":eid,"tensor":key,"shape":list(q.shape),
                "zero_fraction":float(np.mean(q==0)),
                "cl8_bytes_with_row_scales":len(clb)+scales,
                "two_bit_zlib_bytes_with_row_scales":two_bit_zlib(q)+scales,
                "image_like_two_bitplane_zlib_bytes_with_row_scales":bitplanes(q)+scales,
                "marginal_ternary_entropy":entropy(np.bincount(q.ravel()+1,minlength=3))}
        if base is None:
            base=q; anchor_bytes=len(clb)+scales
        else:
            info=cond_entropy(base,q)
            diff=(q.astype(np.int16)-base.astype(np.int16))
            # zlib-delta encodes five levels -2,-1,0,1,2 into bytes.
            dbytes=len(zlib.compress((diff+2).astype(np.uint8).tobytes(),9))+12+scales
            record["video_like_residual_zlib_bytes_with_scales"]=dbytes
            record.update(info)
            delta_bytes+=dbytes
        total+=record["cl8_bytes_with_row_scales"]
        records.append(record)
    model={"model":MODEL,"revision":rev,"checkpoint_sha256":dig.hexdigest(),
           "method":"REAL trained Switch MoE experts then naive row-wise 88.5% zero ternarization",
           "identity":"same decoder block 1, all 8 independently pretrained expert wi weights",
           "expert_count":len(records),
           "uncoded_cl8_total_bytes":total,
           "video_anchor_plus_7_delta_zlib_bytes":anchor_bytes+delta_bytes,
           "video_vs_cl8_percent":100*(1-(anchor_bytes+delta_bytes)/total),
           "mean_mi_bits":float(np.mean([x["mutual_information_bits_per_cell"] for x in records[1:]])),
           "mean_h_cond_bits":float(np.mean([x["conditional_entropy_bits_per_cell"] for x in records[1:]])),
           "warnings":["No original-QMoE checkpoint / no QMoE quantization",
                       "No seq2seq quality/perplexity tested",
                       "No GPU/Android latency tested",
                       "Bitplanes and deltas are storage-only baselines (would require decoding)"],
           "experts":records}
    out=pathlib.Path("results/calibri_v10_multiexpert_real.json")
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps(model,indent=2))
    print(json.dumps({k:model[k] for k in ("model","expert_count","uncoded_cl8_total_bytes",
      "video_anchor_plus_7_delta_zlib_bytes","video_vs_cl8_percent","mean_mi_bits",
      "mean_h_cond_bits")},indent=2),flush=True)

if __name__=="__main__":main()
